import { createHash } from 'node:crypto';
import type { Bundle, ContextDoc, Rule } from './types.js';

export function compile(docs: ContextDoc[], now = new Date()): Bundle {
  const active = docs.filter((d) => d.status === 'active');
  const rulesBySubject: Record<string, Rule[]> = {};
  for (const doc of active) {
    if (doc.rule === undefined) continue;
    const list = rulesBySubject[doc.rule.subject] ?? [];
    list.push(doc.rule);
    rulesBySubject[doc.rule.subject] = list;
  }
  return {
    version: hash(active),
    generatedAt: now.toISOString(),
    docCount: active.length,
    docs: active,
    rulesBySubject,
  };
}

/**
 * Hash the content, not the build time, so an unchanged context compiles to the
 * same version and an agent run can be pinned to it.
 */
function hash(docs: ContextDoc[]): string {
  const h = createHash('sha256');
  for (const d of [...docs].sort((a, b) => a.id.localeCompare(b.id))) {
    h.update(`${d.id}\u0000${d.kind}\u0000${d.scope.join(',')}\u0000${JSON.stringify(d.rule ?? null)}\u0000${d.body}\u0000`);
  }
  return h.digest('hex').slice(0, 12);
}

const ORDER = ['rule', 'deprecation', 'ownership', 'incident', 'decision', 'taste'];

export function byPriority(a: ContextDoc, b: ContextDoc): number {
  return ORDER.indexOf(a.kind) - ORDER.indexOf(b.kind) || a.id.localeCompare(b.id);
}

export function renderBundle(bundle: Bundle): string {
  const lines: string[] = [
    '<!-- Generated by ctxc. Do not edit: edit the sources under your context directory. -->',
    `# Compiled context \`${bundle.version}\``,
    '',
    `${bundle.docCount} active documents, compiled ${bundle.generatedAt}.`,
    '',
  ];
  for (const kind of ORDER) {
    const docs = bundle.docs.filter((d) => d.kind === kind);
    if (docs.length === 0) continue;
    lines.push(`## ${kind}s`, '');
    for (const doc of docs.sort(byPriority)) lines.push(renderDoc(doc), '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export function renderDoc(doc: ContextDoc): string {
  const head = `### ${doc.title} \`${doc.id}\``;
  const meta = [`owner: ${doc.owner}`];
  if (doc.scope.length > 0) meta.push(`scope: ${doc.scope.join(', ')}`);
  if (doc.expires !== undefined) meta.push(`expires: ${doc.expires}`);
  if (doc.incident !== undefined) meta.push(`incident: ${doc.incident}`);
  const rule =
    doc.rule === undefined
      ? []
      : [`**${doc.rule.directive.toUpperCase()}** ${doc.rule.subject} = \`${doc.rule.value}\``, ''];
  return [head, '', `_${meta.join(' · ')}_`, '', ...rule, doc.body].join('\n').trimEnd();
}
